"""Compare every generated contract schema with its published bytes."""

import argparse
from pathlib import Path


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--generated", type=Path, nargs="+", required=True)
    parser.add_argument("--expected", type=Path, nargs="+", required=True)
    args = parser.parse_args()
    generated = {path.name: path for path in args.generated}
    expected = {path.name: path for path in args.expected}
    if generated.keys() != expected.keys():
        raise SystemExit("Generated and published schema sets differ")
    for name, path in expected.items():
        if path.read_bytes() != generated[name].read_bytes():
            raise SystemExit(f"{name}: generated bytes differ from the published schema")
    print(f"{len(expected)} generated schemas equal their published bytes")
