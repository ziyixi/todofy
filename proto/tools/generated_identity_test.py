"""Verify generated module headers name the source that owns each declared output path."""

import re
import sys
from pathlib import Path


def expected_source(path: str) -> str:
    for root in ("proto/ts/", "proto/python/src/ziyixi_proto/"):
        if path.startswith(root):
            module = path[len(root) :]
            for suffix in ("_pb.ts", "_wire.ts", "_pb.py"):
                if module.endswith(suffix):
                    return module[: -len(suffix)] + ".proto"
    raise ValueError(f"Not a generated module output: {path}")


if __name__ == "__main__":
    for filename in sys.argv[1:]:
        text = Path(filename).read_text(encoding="utf-8")
        pattern = (
            r"@generated from file (\S+\.proto) "
            if filename.endswith("_pb.ts")
            else r"Generated by proto/tools/\S+ from proto/(\S+\.proto)\."
        )
        match = re.search(pattern, text)
        expected = expected_source(filename)
        if match is None or match[1] != expected:
            observed = match[1] if match else "missing generation header"
            raise SystemExit(f"{filename}: expected {expected}, found {observed}")
    print(f"Verified source identity for {len(sys.argv) - 1} generated modules")
